"""准时关窗发射（已实现）

全局唯一口径：**关闭即冻结（甲）**。

关窗是跨「水位线 / 热度窗 / 事件入流」的状态机。本模块是该口径的唯一权威定义，
底座主链（services.热度窗 / services.装载 / services.关窗发射）与只读接口均贯彻此口径。

口径甲·关闭即冻结
------------------
1. 水位 >= 窗止：关窗事务（写闸、单提交）把窗 开启→已关闭，并在同一事务内物化发射快照
   （点赞/送礼/笔数/版本/发射号/关闭时水位），写「关窗发射」记录。发射结果可核对。
2. 关窗后同窗事件按处理时分流：
   - 准时（处理时 <= 关闭处理时，即关窗前已在途的同窗事件）→ **拒收**。
     事件命运=关闭拒收、不挂窗键，写「关窗拒收」证据；窗合计与发射快照都不变。
   - 迟到（处理时 > 关闭处理时，且水位未过 窗止+允许迟到）→ 显式迟到修正路径，
     走撤回单链改现行合计；发射快照保持不动（快照是关窗瞬间的留痕）。
   - 水位 >= 窗止+允许迟到 → 旁路匣（既有规则不变）。
3. 并发交错失败闭：关窗写闸以 状态='开启' 为条件，配合写锁，关窗与入流不可能各做一半；
   任何中途异常整批回滚，绝不留下「状态已关闭、合计继续被准时路径累加」的分叉。

被否决的另一口径（乙·关闭可续写）：关闭只表示发射过，同窗准时事件仍累加现行合计并写续写
审计。本系统**不实现、禁止混入**；两口径对「关窗后只推同窗准时事件」的结论相反——
甲：合计不变且拒收；乙：合计增加且有续写审计。这里固定为甲。
"""

状态 = "已实现"

# 全局唯一口径标识。任何写闸/入流路径读到非此值都必须失败闭，而不是静默走另一口径。
关窗口径 = "关闭即冻结"

# 关窗后准时事件的处置（甲口径下唯一合法值）。
准时处置 = "拒收"

# 互动事件.命运 的新增取值。
命运_关闭拒收 = "关闭拒收"


def 断言口径(站规: dict | None = None) -> None:
    """架构守卫：全局只贯彻「关闭即冻结」。读到乙口径或被污染的配置直接失败闭。"""
    if 站规 is not None:
        实际 = 站规.get("关窗口径")
        if 实际 is not None and 实际 != 关窗口径:
            raise RuntimeError(
                f"关窗口径冲突：站规={实际!r}，本系统全局只贯彻 {关窗口径!r}（禁止关闭可续写混入）"
            )


def 是关窗后准时(事件处理时: str, 关闭处理时: str) -> bool:
    """甲口径分流判据。

    处理时 <= 关闭处理时：关窗事务提交前已在途的同窗事件 → 准时，冻结口径下拒收。
    处理时 >  关闭处理时：关窗后才到达 → 迟到，交由显式迟到修正（撤回单）路径。
    """
    from app.services import 时间

    return 时间.解析(事件处理时) <= 时间.解析(关闭处理时)
